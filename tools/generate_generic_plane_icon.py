# Regenerates src/render/GenericPlaneImg.cpp from tools/generic_plane_icon.png - the fallback graphic
# FlightScreen.cpp's TwoUp/OneUp cards show in place of an airline logo (no logo exists for non-commercial
# traffic, or a commercial logo that hasn't finished downloading yet - see LogoStore.h). Baked into flash at
# compile time (unlike airline logos, which LogoStore downloads into LittleFS on demand) since this one
# graphic is static and always needed, the same "checked-in generated table" precedent
# generate_airport_table.py already set for AirportData.cpp.
#
# Usage: python3 tools/generate_generic_plane_icon.py
# (run from the project root; needs Pillow: python3 -m pip install pillow)
import os

from PIL import Image

SRC_PNG = os.path.join(os.path.dirname(__file__), "generic_plane_icon.png")
OUT_CPP = os.path.join(os.path.dirname(__file__), "..", "src", "render", "GenericPlaneImg.cpp")
SIZE = 70  # matches LogoStore's airline-logo footprint (LogoStore.cpp's kLogo) - same card layout slot


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    im = Image.open(SRC_PNG).convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
    pixels = list(im.getdata())

    lines = []
    for i in range(0, len(pixels), SIZE):
        row_vals = []
        for (r, g, b) in pixels[i:i + SIZE]:
            v = rgb565(r, g, b)
            row_vals.append(f"{v & 0xFF:#04x},{(v >> 8) & 0xFF:#04x}")  # little-endian, matches LogoStore.cpp
        lines.append("    " + ",".join(row_vals) + ",")

    with open(OUT_CPP, "w") as f:
        f.write(
            "// GENERATED by tools/generate_generic_plane_icon.py from tools/generic_plane_icon.png - do not "
            "edit by hand.\n"
            "#include \"GenericPlaneImg.h\"\n\n"
            "namespace {\n"
            f"const uint8_t kData[] = {{\n"
        )
        f.write("\n".join(lines))
        f.write(
            "\n};\n"
            "}  // namespace\n\n"
            "const lv_image_dsc_t kGenericPlaneImg = {\n"
            "    .header = {\n"
            "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            "        .cf = LV_COLOR_FORMAT_RGB565,\n"
            "        .flags = 0,\n"
            f"        .w = {SIZE},\n"
            f"        .h = {SIZE},\n"
            f"        .stride = {SIZE * 2},\n"
            "        .reserved_2 = 0,\n"
            "    },\n"
            "    .data_size = sizeof(kData),\n"
            "    .data = kData,\n"
            "    .reserved = nullptr,\n"
            "    .reserved_2 = nullptr,\n"
            "};\n"
        )
    print(f"wrote {OUT_CPP} ({SIZE}x{SIZE}, {len(pixels) * 2} B pixel data)")


if __name__ == "__main__":
    main()
